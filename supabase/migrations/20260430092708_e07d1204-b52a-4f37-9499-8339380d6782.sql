-- =========================================================
-- profiles
-- =========================================================
CREATE TABLE public.profiles (
  id uuid NOT NULL,
  email text NULL,
  full_name text NULL,
  created_at timestamp with time zone NULL DEFAULT now(),
  professions text[] NULL DEFAULT '{}'::text[],
  interests text[] NULL DEFAULT '{}'::text[],
  city text NULL,
  country text NULL,
  latitude double precision NULL,
  longitude double precision NULL,
  location_updated_at timestamp with time zone NULL,
  CONSTRAINT profiles_pkey PRIMARY KEY (id),
  CONSTRAINT profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id) ON DELETE CASCADE
);

-- =========================================================
-- user_roles  (text role, one per user)
-- =========================================================
CREATE TABLE public.user_roles (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id uuid NULL,
  role text NULL DEFAULT 'user'::text,
  created_at timestamp without time zone NULL DEFAULT now(),
  CONSTRAINT user_roles_pkey PRIMARY KEY (id),
  CONSTRAINT user_roles_user_id_key UNIQUE (user_id),
  CONSTRAINT user_roles_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE,
  CONSTRAINT user_roles_role_check CHECK ((role = ANY (ARRAY['user'::text, 'admin'::text])))
);

