CREATE POLICY "news read authenticated"
  ON public.news FOR SELECT TO authenticated
  USING (true);
CREATE POLICY "news insert admin"
  ON public.news FOR INSERT TO authenticated
  WITH CHECK (public.is_admin(auth.uid()));
CREATE POLICY "news update admin"
  ON public.news FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid()));
CREATE POLICY "news delete admin"
  ON public.news FOR DELETE TO authenticated
  USING (public.is_admin(auth.uid()));

-- saved_articles: user manages own; admin can view all
CREATE POLICY "saved select own or admin"
  ON public.saved_articles FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.is_admin(auth.uid()));
CREATE POLICY "saved insert own"
  ON public.saved_articles FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid());
CREATE POLICY "saved delete own or admin"
  ON public.saved_articles FOR DELETE TO authenticated
  USING (user_id = auth.uid() OR public.is_admin(auth.uid()));

