  id uuid NOT NULL DEFAULT gen_random_uuid(),
  title text NULL,
  description text NULL,
  image_url text NULL,
  url text NULL,
  source text NULL,
  category text NULL DEFAULT 'general'::text,
  created_at timestamp with time zone NULL DEFAULT now(),
  key_points jsonb NULL,
  action_points jsonb NULL,
  summary text NULL,
  country text NULL,
  state text NULL,
  district text NULL,
  taluka text NULL,
  city text NULL,
  pincode varchar(10) NULL,
  created_by uuid NULL,  -- NEW: ownership column for reporter scoping
  CONSTRAINT news_pkey PRIMARY KEY (id),
  CONSTRAINT news_url_key UNIQUE (url)
);
CREATE INDEX IF NOT EXISTS idx_news_location
  ON public.news USING btree (country, state, district, city);
CREATE INDEX IF NOT EXISTS idx_news_created_by ON public.news (created_by);
CREATE INDEX IF NOT EXISTS idx_news_created_at ON public.news (created_at DESC);

