-- NEWS: any authenticated reads; admins do all; reporters manage own
CREATE POLICY "news read authenticated" ON public.news
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "news insert admin or reporter own" ON public.news
  FOR INSERT TO authenticated
  WITH CHECK (public.is_admin(auth.uid()) OR (public.has_role('reporter') AND created_by = auth.uid()));
CREATE POLICY "news update admin or own" ON public.news
  FOR UPDATE TO authenticated
  USING (public.is_admin(auth.uid()) OR created_by = auth.uid());
CREATE POLICY "news delete admin or own" ON public.news
  FOR DELETE TO authenticated
  USING (public.is_admin(auth.uid()) OR created_by = auth.uid());

